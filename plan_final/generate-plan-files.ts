async function writeText(path: string, text: string): Promise<void> {
  await Bun.write(path, text);
}

export async function generatePlanFiles(): Promise<void> {
  await mkdir('plan_final/steps', { recursive: true });
  await mkdir('plan_final/status', { recursive: true });
  await mkdir('plan_final/progress/governance', { recursive: true });
  await mkdir('plan_final/evidence', { recursive: true });
  await mkdir('plan_final/lane_locks', { recursive: true });

  await writeText('plan_final/evidence/.gitkeep', TRACKED_DIRECTORY_PLACEHOLDER);
  await writeText('plan_final/lane_locks/.gitkeep', TRACKED_DIRECTORY_PLACEHOLDER);
  await writeText('plan_final/status/.gitkeep', TRACKED_DIRECTORY_PLACEHOLDER);

  await writeText('plan_final/README.md', readmeMarkdown());
  await writeText('plan_final/PROMPT.md', promptMarkdown());
  await writeText('plan_final/PRE_PROMPT.md', prePromptMarkdown());
  await writeText('plan_final/STEP_TEMPLATE.md', stepTemplateMarkdown());
  await writeText('plan_final/PARALLEL_WORK.md', parallelWorkMarkdown());
  await writeText('plan_final/DEPENDENCY_GRAPH.md', dependencyGraphMarkdown());
  await writeText('plan_final/MASTER_CHECKLIST.md', checklistMarkdown());

  for (const lane of FINAL_PLAN_LANES) {
    await mkdir(`plan_final/progress/${lane.lane}`, { recursive: true });
    if (lane.lane !== 'governance') {
      await writeText(`plan_final/progress/${lane.lane}/.gitkeep`, TRACKED_DIRECTORY_PLACEHOLDER);
    }
  }

  for (const stepDefinition of FINAL_PLAN_STEPS) {
    await writeText(stepPath(stepDefinition), stepMarkdown(stepDefinition));
  }

  await writeText(
    'plan_final/progress/governance/00-001.md',
    [
      '# 00-001 create-final-control-center',
      '',
      '- Started control-center creation.',
      '- Generated plan files, lane progress directories, and step files from planData.ts.',
      '- Focused verification target: test/plan_final/validate-plan.test.ts.',
      '',
    ].join('\n'),
  );
}

if (import.meta.main) {
  await generatePlanFiles();
}
