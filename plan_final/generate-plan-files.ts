import { mkdir } from 'node:fs/promises';

import { FINAL_PLAN_LANES, FINAL_PLAN_STEP_COUNT, FINAL_PLAN_STEPS, type FinalPlanStep } from './planData.ts';

const GENERATED_NOTICE = '<!-- Generated by plan_final/generate-plan-files.ts. Edit planData.ts, then regenerate. -->';
const TRACKED_DIRECTORY_PLACEHOLDER = 'tracked directory placeholder\n';

function bulletList(values: readonly string[]): string {
  if (values.length === 0) {
    return '- none';
  }

  return values.map((value) => `- ${value}`).join('\n');
}

function slugify(value: string): string {
  return value.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-').replaceAll(/^-|-$/g, '');
}

function stepPath(step: FinalPlanStep): string {
  return `plan_final/steps/${step.id}-${slugify(step.title)}.md`;
}

